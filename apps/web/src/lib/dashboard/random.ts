/**
 * Deterministic pseudo-random helpers shared by the sample-data layer.
 *
 * The dashboard has no live API yet, so every generated dataset is seeded and
 * reproducible: the same seed always yields the same stream. This keeps sample
 * analytics stable across server renders instead of shuffling on every request.
 */

/** Deterministic 32-bit PRNG (mulberry32). Returns floats in [0, 1). */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** djb2 string hash — used to derive stable numeric seeds from identifiers. */
export function hashString(value: string): number {
  let hash = 5381;
  for (let i = 0; i < value.length; i++) {
    hash = ((hash << 5) + hash + value.charCodeAt(i)) >>> 0;
  }
  return hash;
}
